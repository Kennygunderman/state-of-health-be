CREATE INDEX "idx_catalog_foods_fold_display_name" ON "catalog_foods"(translate("display_name", 'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'abcdefghijklmnopqrstuvwxyz') text_pattern_ops) WHERE "publication_status" = 'published';

