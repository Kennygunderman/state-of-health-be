CREATE INDEX "idx_catalog_food_aliases_fold_alias" ON "catalog_food_aliases"(translate("alias", 'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'abcdefghijklmnopqrstuvwxyz') text_pattern_ops);

